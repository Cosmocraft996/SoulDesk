import { createRoot } from 'react-dom/client';
import { App } from './App';
import { DesktopProbe } from './DesktopProbe';
import { WidgetFrame } from './WidgetFrame';
import './style.css';
import './app-theme.css';
import './official-gallery.css';

const probeKind = new URLSearchParams(location.search).get('desktopProbe');
const probe = probeKind !== null && ['clock', 'card', 'panel', 'trial'].includes(probeKind);
const keyboardOverlay = new URLSearchParams(location.search).get('keyboardOverlay');
const noticeOverlay = new URLSearchParams(location.search).get('noticeOverlay');
const breakOverlay = new URLSearchParams(location.search).get('breakOverlay');
const clipboardPopup = new URLSearchParams(location.search).get('clipboardPopup');
const assistantPanel = new URLSearchParams(location.search).get('assistantPanel');
const jobPanel = new URLSearchParams(location.search).get('jobPanel');
const pomodoroWindow = new URLSearchParams(location.search).get('pomodoroWindow');
if (pomodoroWindow) document.documentElement.dataset.surface = 'pomodoro';
if (jobPanel) document.documentElement.dataset.surface = 'job';
if (assistantPanel) document.documentElement.dataset.surface = 'assistant';
if (clipboardPopup) document.documentElement.dataset.surface = 'clipboard';
if (noticeOverlay || breakOverlay) document.documentElement.dataset.surface = 'reminder';
if (keyboardOverlay) document.documentElement.dataset.surface = 'keyboard';
if (probe) document.documentElement.dataset.desktopProbe = probeKind;
createRoot(document.getElementById('root')!).render(pomodoroWindow ? <WidgetFrame instance={pomodoroWindow} page="clock" /> : jobPanel ? <WidgetFrame instance={jobPanel} page="job-panel" jobShell /> : assistantPanel ? <WidgetFrame instance={assistantPanel} page="assistant-panel" assistantShell /> : clipboardPopup ? <WidgetFrame instance={clipboardPopup} page={new URLSearchParams(location.search).get('page') ?? 'clipboard-history'} /> : noticeOverlay || breakOverlay ? <WidgetFrame instance={noticeOverlay ?? breakOverlay!} page={noticeOverlay ? 'notification-overlay' : 'break-overlay'} /> : keyboardOverlay ? <WidgetFrame instance={keyboardOverlay} page="keyboard-overlay"/> : probeKind === 'trial' ? <WidgetFrame probe instance={new URLSearchParams(location.search).get('instance') ?? ''} /> : probe ? <DesktopProbe kind={probeKind} /> : <App />);
