import { createApp } from 'vue';
import { connectHost } from '../../../sdk/host.js';
import App from './App.vue';
import { Tooltip } from './icons';
import './style.css';
const host = await connectHost();
const settings = await host.request('settings.get');
const app = createApp(App, { host, initialSettings:settings, variant:document.body.dataset.variant || 'weather-small' });
app.component('el-tooltip', Tooltip);
app.mount('#app');
window.addEventListener('pagehide', () => app.unmount(), {once:true});
