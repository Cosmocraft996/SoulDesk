import { createApp } from 'vue';
import App from './App.vue';
import { ComponentFrame, settings, status } from './souldesk';
import { connectHost } from '../../../sdk/host.js';
import './style.css';
const host = await connectHost();
Object.assign(settings, await host.request('settings.get'));
const variant = document.body.dataset.variant || 'clock';
const app = createApp(App, { host, variant });
app.component('component-frame', ComponentFrame);
app.config.errorHandler = error => { status.error = true; status.message = '组件错误：' + String(error); throw error; };
app.mount('#app');
const resize = () => {
  const root = document.getElementById('clock-root')!;
  root.style.setProperty('--widget-inner-width', innerWidth + 'px');
  root.style.setProperty('--widget-inner-height', innerHeight + 'px');
  root.style.setProperty('--mickey-scale', String(Math.min(innerWidth, innerHeight) / 560));
};
resize();
window.addEventListener('resize', resize);
window.addEventListener('pagehide', () => { window.removeEventListener('resize', resize); app.unmount(); }, { once: true });
