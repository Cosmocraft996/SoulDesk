import { createApp, nextTick } from 'vue';
import { connectHost } from '../../../sdk/host.js';
import App from './App.vue';
import { setHost, settings, contentFailure } from './native';
import './style.css';
const host = await connectHost();
setHost(host);
Object.assign(settings, await host.request('settings.get'));
const app = createApp(App, { host });
app.config.errorHandler = contentFailure;
app.mount('#app');
await nextTick(); await host.ready();
window.addEventListener('pagehide', () => app.unmount(), { once: true });
