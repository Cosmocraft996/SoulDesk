import { createRoot } from 'react-dom/client';
import { connectHost } from '../../../sdk/host.js';
import { setFileHost } from './file-access.js';
import { restoreScene } from './scene-model.js';
import App from './App';
const host = await connectHost();
const stored = await host.request('storage.get');
restoreScene(stored);
setFileHost(host);
window.open = (url?:string|URL) => { if(!host.preview && url) host.request('links.open',{url:String(url)}).catch((error:Error)=>console.error('网页未打开：',error.message)); return null; };
const root = createRoot(document.getElementById('root')!);
let ready = false;
root.render(<App host={host} stored={stored} onReady={()=>{ if(!ready){ready=true;void host.ready();} }} />);
window.addEventListener('pagehide',()=>root.unmount(),{once:true});
